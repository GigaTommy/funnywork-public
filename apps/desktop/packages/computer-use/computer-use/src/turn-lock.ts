/** One provider owns complete desktop workflows until their turn and native calls settle. */

import { randomUUID } from 'node:crypto'
import type { Context } from '@deepseek-ai/cordis'
import type { Agent } from '@deepseek-ai/dsh-agent'
import type { Session } from '@deepseek-ai/dsh-session'
import type { ToolExecution } from '@deepseek-ai/dsh-tools'
import { acquireDesktopProcessLease, DesktopProcessBusyError, type DesktopProcessLease, type DesktopProcessLeaseOptions } from './process-lease.ts'

interface Turn {
  number: number
  signal: AbortSignal
}

class DesktopOwnershipError extends Error {
  constructor(readonly code: 'COMPUTER_BUSY' | 'COMPUTER_CLEANUP_FAILED', message: string, options?: ErrorOptions) {
    super(`${code}: ${message}`, options)
    this.name = 'DesktopOwnershipError'
  }
}

/** Native session identity generated by the host rather than selected by tool arguments. */
type NativeSession = string & { readonly nativeSession: unique symbol }

/** The native call receives only its owner's identity and fused cancellation. */
export interface DesktopLease {
  readonly nativeSession: NativeSession
  readonly signal: AbortSignal
  usedNativeSession: boolean
}

interface Owner extends DesktopLease {
  agent: Agent | undefined
  session: Session | undefined
  turn: number | undefined
  controller: AbortController
  pending: number
  closing: boolean
  closed: Promise<void> | undefined
  tail: Promise<void>
  detachTurnAbort: () => void
  processLease: Promise<DesktopProcessLease> | undefined
}

/** Holds one turn's desktop ownership and serializes its calls through native settlement. */
export class DesktopTurnLock {
  private readonly turns = new WeakMap<Agent, Turn>()
  private owner: Owner | undefined
  private failure: Error | undefined

  /**
   * @param ctx - provider-owned context whose lifecycle events fence desktop ownership.
   * @param endNativeSession - cleanup awaited before another turn may enter; never receives an aborted turn signal.
   */
  constructor(
    private readonly ctx: Context,
    private readonly endNativeSession: (lease: DesktopLease) => Promise<void>,
    private readonly processLeaseOptions?: DesktopProcessLeaseOptions,
  ) {
    ctx.on('agent/pre-step', async (payload, next) => {
      this.turns.set(payload.agent, { number: payload.turn, signal: payload.signal })
      return next()
    })
    ctx.on('session/event', (session, event) => {
      if (event.type === 'turn/end' && this.owner?.session === session && this.owner.turn === event.data.turn) this.close(this.owner)
    })
    ctx.on('session/disposed', (session) => {
      if (this.owner?.session === session) this.close(this.owner)
    })
    ctx.on('agent/disposed', ({ agent }) => {
      this.turns.delete(agent)
      if (this.owner?.agent === agent) this.close(this.owner)
    })
  }

  /** Whether another desktop workflow or its cleanup still owns the provider. */
  get busy(): boolean {
    return this.owner !== undefined
  }

  /** Cleanup failures stop subsequent desktop work until the provider restarts. */
  get cleanupFailure(): string | undefined {
    return this.failure?.message
  }

  private assertHealthy(): void {
    if (this.failure !== undefined) throw this.failure
  }

  /**
   * Run one serialized call while retaining ownership between calls of the same live turn.
   * Agent-less calls and calls outside a known turn retain ownership only through this invocation.
   * @param exec - immutable tool identity and caller cancellation.
   * @param operation - native operation, completed before cancellation can release ownership.
   * @returns the operation result or an explicit busy, cancellation, or cleanup failure.
   */
  async run<T>(exec: ToolExecution, operation: (lease: DesktopLease) => Promise<T>): Promise<T> {
    exec.signal.throwIfAborted()
    this.assertHealthy()
    if (this.owner?.closing && this.owner.closed !== undefined) await this.owner.closed
    exec.signal.throwIfAborted()
    this.assertHealthy()
    const turn = exec.agent === undefined ? undefined : this.turns.get(exec.agent)
    turn?.signal.throwIfAborted()
    let owner = this.owner
    if (owner !== undefined && (owner.closing || owner.agent !== exec.agent || turn === undefined || owner.turn !== turn.number)) {
      throw new DesktopOwnershipError('COMPUTER_BUSY', 'another session owns the desktop until its current turn finishes; retry with a fresh observation afterward')
    }
    if (owner === undefined) {
      const controller = new AbortController()
      owner = {
        agent: exec.agent,
        session: exec.agent?.session,
        turn: turn?.number,
        nativeSession: `computer-${randomUUID()}` as NativeSession,
        controller,
        signal: controller.signal,
        usedNativeSession: false,
        pending: 0,
        closing: false,
        closed: undefined,
        tail: Promise.resolve(),
        detachTurnAbort: () => {},
        processLease: undefined,
      }
      this.owner = owner
      if (this.processLeaseOptions !== undefined) {
        owner.processLease = acquireDesktopProcessLease(this.processLeaseOptions, controller.signal)
      }
      if (turn !== undefined) {
        const selected = owner
        const abort = () => { this.close(selected) }
        turn.signal.addEventListener('abort', abort, { once: true })
        owner.detachTurnAbort = () => { turn.signal.removeEventListener('abort', abort) }
      }
    }
    const selected = owner
    const abort = () => { this.close(selected) }
    exec.signal.addEventListener('abort', abort, { once: true })
    const previous = owner.tail
    owner.pending += 1
    const running = previous.then(async () => {
      try {
        await selected.processLease
      } catch (error) {
        this.close(selected)
        if (error instanceof DesktopProcessBusyError) throw new DesktopOwnershipError('COMPUTER_BUSY', error.message, { cause: error })
        throw error
      }
      const signal = AbortSignal.any([exec.signal, selected.signal])
      signal.throwIfAborted()
      const lease: DesktopLease = {
        nativeSession: selected.nativeSession,
        signal,
        get usedNativeSession() { return selected.usedNativeSession },
        set usedNativeSession(value) { selected.usedNativeSession = value },
      }
      return await operation(lease)
    })
    owner.tail = running.then(() => {}, () => {})
    try {
      return await running
    } finally {
      exec.signal.removeEventListener('abort', abort)
      owner.pending -= 1
      if (turn === undefined) this.close(owner)
      if (owner.closing) this.finish(owner)
    }
  }

  /** Abort queued calls and await admitted calls and native-session cleanup. */
  async dispose(): Promise<void> {
    const owner = this.owner
    if (owner === undefined) return
    this.close(owner)
    await owner.tail
    this.finish(owner)
    await owner.closed
  }

  private close(owner: Owner): void {
    owner.closing = true
    owner.controller.abort()
    this.finish(owner)
  }

  private finish(owner: Owner): void {
    if (owner.pending !== 0 || owner.closed !== undefined) return
    owner.detachTurnAbort()
    owner.closed = (async () => {
      try {
        if (owner.usedNativeSession) await this.endNativeSession(owner)
        // Failed acquisition owns no native input. Failed native cleanup intentionally
        // leaves the OS-user lease held until process exit, preventing unsafe handoff.
        const lease = await owner.processLease?.catch(() => undefined)
        await lease?.release()
      } catch (error) {
        this.failure = new DesktopOwnershipError('COMPUTER_CLEANUP_FAILED', 'the previous native session could not close; restart the host before operating the desktop', { cause: error })
        this.ctx.logger.warn(this.failure.message)
      } finally {
        if (this.owner === owner) this.owner = undefined
      }
    })()
  }
}
