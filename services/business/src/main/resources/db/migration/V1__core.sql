CREATE TABLE nodes (
  id VARCHAR(64) PRIMARY KEY REFERENCES principals(id), tenant_id VARCHAR(64) NOT NULL,
  zone VARCHAR(64) NOT NULL, capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 16),
  capability VARCHAR(80) NOT NULL, status VARCHAR(16) NOT NULL,
  last_seen BIGINT NOT NULL
);
CREATE TABLE agent_versions (
  id VARCHAR(64) PRIMARY KEY, tenant_id VARCHAR(64) NOT NULL, name VARCHAR(100) NOT NULL,
  version VARCHAR(40) NOT NULL, capability VARCHAR(80) NOT NULL,
  status VARCHAR(16) NOT NULL, created_by VARCHAR(64) NOT NULL REFERENCES principals(id),
  UNIQUE (tenant_id, name, version)
);
CREATE TABLE tasks (
  id VARCHAR(64) PRIMARY KEY, tenant_id VARCHAR(64) NOT NULL,
  owner_id VARCHAR(64) NOT NULL REFERENCES principals(id), owner_auth_version BIGINT NOT NULL,
  zone VARCHAR(64) NOT NULL, agent_id VARCHAR(64) NOT NULL REFERENCES agent_versions(id),
  state VARCHAR(24) NOT NULL, request_key VARCHAR(120) NOT NULL, request_hash VARCHAR(64) NOT NULL,
  created_at BIGINT NOT NULL, UNIQUE (tenant_id, owner_id, request_key)
);
CREATE TABLE work_units (
  id VARCHAR(64) PRIMARY KEY, task_id VARCHAR(64) NOT NULL REFERENCES tasks(id),
  ordinal INTEGER NOT NULL, input_text TEXT NOT NULL, state VARCHAR(24) NOT NULL,
  epoch BIGINT NOT NULL DEFAULT 0, attempts INTEGER NOT NULL DEFAULT 0,
  UNIQUE(task_id, ordinal)
);
CREATE INDEX units_ready_idx ON work_units(state, task_id, ordinal);
CREATE TABLE attempts (
  id VARCHAR(64) PRIMARY KEY, unit_id VARCHAR(64) NOT NULL REFERENCES work_units(id),
  node_id VARCHAR(64) NOT NULL REFERENCES nodes(id), epoch BIGINT NOT NULL,
  state VARCHAR(24) NOT NULL, expires_at BIGINT NOT NULL, created_at BIGINT NOT NULL,
  UNIQUE(unit_id, epoch)
);
CREATE INDEX attempts_node_idx ON attempts(node_id, state, expires_at);
CREATE TABLE unit_results (
  unit_id VARCHAR(64) PRIMARY KEY REFERENCES work_units(id),
  attempt_id VARCHAR(64) NOT NULL REFERENCES attempts(id), result_json TEXT NOT NULL,
  accepted_at BIGINT NOT NULL
);
CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id VARCHAR(64) NOT NULL, task_id VARCHAR(64), actor_id VARCHAR(64),
  event_type VARCHAR(80) NOT NULL, payload_json TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE INDEX events_task_idx ON events(tenant_id,task_id,id);
