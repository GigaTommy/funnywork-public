CREATE TABLE principals (
  id VARCHAR(64) PRIMARY KEY, tenant_id VARCHAR(64) NOT NULL,
  kind VARCHAR(16) NOT NULL CHECK (kind IN ('USER','NODE')),
  display_name VARCHAR(120) NOT NULL, roles TEXT NOT NULL, zones TEXT NOT NULL,
  enabled BOOLEAN NOT NULL, auth_version BIGINT NOT NULL DEFAULT 1
);
CREATE TABLE api_tokens (
  token_hash VARCHAR(64) PRIMARY KEY, principal_id VARCHAR(64) NOT NULL REFERENCES principals(id),
  expires_at BIGINT NOT NULL, revoked BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE scheduler_guard (id INTEGER PRIMARY KEY);
